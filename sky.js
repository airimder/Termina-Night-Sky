function sins(x) {
  x = (x & 0xffff) >>> 4;
  const val = x & 0x400 ? SINTABLE[0x3ff - (x & 0x3ff)] : SINTABLE[x & 0x3ff];
  return x & 0x800 ? -val : val;
}

const sinS = (a) => f(sins(a) * f(1 / 32767));
const cosS = (a) => f(sins((a & 0xffff) + 0x4000) * f(1 / 32767));

const next = (r) => (Math.imul(r, 1664525) + 1013904223) >>> 0;
// (r >> 9) | 0x3F800000 reinterpreted as a float, minus 1: exactly (r >> 9) / 2^23
const randFloat = (r) => (r >>> 9) / 8388608;

