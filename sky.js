// File-select name entry codes (ovl_file_choose/z_file_nameset_data.c)
export const CHARSET = (() => {
  const m = new Map();
  for (let d = 0; d < 10; d++) m.set(String(d), d);
  for (let k = 0; k < 26; k++) {
    m.set(String.fromCharCode(65 + k), 0x0a + k);
    m.set(String.fromCharCode(97 + k), 0x24 + k);
  }
  m.set(" ", 0x3e);
  m.set("-", 0x3f);
  m.set(".", 0x40);
  return m;
})();

export const NAME_LENGTH = 8;

// Returns the 8 name bytes, padded with spaces, or null if a character can't be typed in-game.
export function encodeName(name) {
  if (name.length > NAME_LENGTH) return null;
  const bytes = [];
  for (const c of name) {
    if (!CHARSET.has(c)) return null;
    bytes.push(CHARSET.get(c));
  }
  while (bytes.length < NAME_LENGTH) bytes.push(0x3e);
  return bytes;
}

export function seedFromBytes(b) {
  return ((b[0] << 24) ^ (b[1] << 20) ^ (b[2] << 16) ^ (b[3] << 12) ^ (b[4] << 8) ^ (b[5] << 4) ^ b[6] ^
    (b[7] >>> 4) ^ (b[7] << 28)) >>> 0;
}

