/**
 * The first `count` stars for a name. Each star: { x, y, z } relative to the camera (game units),
 * width (in quarter pixels, as drawn in-game, 1 px tall), color [r, g, b], fixed (one of the 16 shared stars).
 * `day`: save day counter; star 15 turns orange when day % 7 == 0.
 */
export function generateStars(nameBytes, count, day = 1) {
  let r = seedFromBytes(nameBytes);
  let color = null;
  let paletteIndex = 0;
  const stars = [];

  for (let i = 0; i < count; i++) {
    let x, y, z, width;
    if (i < 16) {
      [x, y, z] = FIXED[i];
      width = 8;
    } else {
      r = next(r);
      const a = randFloat(r);
      r = next(r);
      const t = f(f(randFloat(r) + a) * 0.5);
      r = next(r);
      y = f(f(f(t * t) * 16384) - 1000);
      const radius = f(f(f(1.2) - t) * 16384);
      x = f(sinS(r) * radius);
      z = f(cosS(r) * radius);
      r = next(r);
      const u = randFloat(r);
      width = Math.trunc(f(f(f(u * u) * 8) + 2));
    }

    if (i < 15 || (i === 15 && day % 7 === 0)) {
      color = FIXED_COLORS[i % 8];
    } else if ((i & 0x3f) === 0 || i === 16) {
      color = RANDOM_COLORS[paletteIndex % 16];
      paletteIndex++;
    }

    stars.push({ x, y, z, width, color, fixed: i < 16 });
  }
  return stars;
}

